import { defineConfig, type Plugin } from "vite";

const buildTime = new Date();

/**
 * App version — the SINGLE place to change when switching to a real version scheme.
 * Provisional: build time in Asia/Tokyo as YYYYMMDDHHmm (e.g. 202610131555).
 */
function appVersion(d = buildTime): string {
  const p = Object.fromEntries(
    new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Tokyo", year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit", hourCycle: "h23" })
      .formatToParts(d).map((x) => [x.type, x.value]),
  );
  return `${p.year}${p.month}${p.day}${p.hour}${p.minute}`;
}
const VERSION = appVersion();

/** Emits sw.js (cache name = version, precaches the built files) and version.json (read when an update is waiting). */
function serviceWorker(): Plugin {
  return {
    name: "os-service-worker",
    apply: "build",
    generateBundle(_opts, bundle) {
      const files = ["./", "./manifest.webmanifest", "./icons/icon-192.png", "./icons/icon-512.png", ...Object.keys(bundle).map((f) => "./" + f)];
      const sw = `// generated by vite.config.ts
const VERSION = ${JSON.stringify(VERSION)};
const CACHE = "phone-os-" + VERSION;
const PRECACHE = ${JSON.stringify(files)};
self.addEventListener("install", (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE))); });
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("phone-os-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("message", (e) => {
  if (e.data === "skipWaiting") self.skipWaiting();
  if (e.data === "version") e.source && e.source.postMessage({ version: VERSION });
});
self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== location.origin || url.pathname.endsWith("/version.json")) return;
  if (e.request.mode === "navigate") {
    // network first for the page, cached shell when offline
    e.respondWith(fetch(e.request).catch(() => caches.match("./", { ignoreSearch: true })));
    return;
  }
  e.respondWith(caches.match(e.request).then((r) => r || fetch(e.request)));
});
`;
      this.emitFile({ type: "asset", fileName: "sw.js", source: sw });
      this.emitFile({ type: "asset", fileName: "version.json", source: JSON.stringify({ version: VERSION, builtAt: buildTime.toISOString() }) });
    },
  };
}

export default defineConfig({
  base: "/phone/",
  build: { target: "es2022" },
  plugins: [serviceWorker()],
  define: {
    // "update date" used by the battery model = build time
    __UPDATE_DATE__: JSON.stringify(buildTime.toISOString()),
    __APP_VERSION__: JSON.stringify(VERSION),
  },
});
